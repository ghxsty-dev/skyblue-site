/** 9x9 özel simge hücresinden slot girdisi üretir. */
export function customSlotInput(cells: CustomIconCells): RankSlotInput {
  return {
    width: cells.length,
    rows: cells.map((row) => row.map((cell) => (cell ? "1" : "0")).join("")),
    colors: cells,
  };
}

