export function getPixelFont(id: string): PixelFont {
  return PIXEL_FONTS.find((font) => font.id === id) || PIXEL_FONTS[0];
}

export function normalizeRankText(value: string): string {
  const normalized = value
    .trim()
    .toUpperCase()
    .replace(/[İI]/g, "I")
    .replace(/Ş/g, "S")
    .replace(/Ğ/g, "G")
    .replace(/Ü/g, "U")
    .replace(/Ö/g, "O")
    .replace(/Ç/g, "C");

  return Array.from(normalized, (character) => RANK_CHARACTERS.has(character) ? character : "?")
    .join("")
    .slice(0, 32);
}

export function buildPixelText(font: PixelFont, value: string) {
  const text = normalizeRankText(value) || "VIP";
  const rows = Array.from({ length: font.height }, () => [] as string[]);

  for (const character of text) {
    const glyph = font.glyphs[character] || font.glyphs["?"];
    const glyphWidth = glyph[0]?.length || 1;
    for (let row = 0; row < font.height; row += 1) rows[row].push(glyph[row] || "0".repeat(glyphWidth));
    for (let row = 0; row < font.height; row += 1) rows[row].push("0");
  }

  return {
    text,
    rows: rows.map((row) => row.slice(0, -1).join("")),
    width: rows[0].join("").length - 1,
    height: font.height,
  };
}
